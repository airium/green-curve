static std::string shell_quote_single(const char* text) {
    std::string out;
    out.push_back('\'');
    if (text) {
        for (const char* p = text; *p; ++p) {
            if (*p == '\'') out += "'\"'\"'";
            else out.push_back(*p);
        }
    }
    out.push_back('\'');
    return out;
}

bool write_linux_assets(const char* outputDir, const char* execPath, const char* configPath, char* err, size_t errSize) {
    if (!outputDir || !*outputDir || !execPath || !*execPath || !configPath || !*configPath) {
        set_message(err, errSize, "Missing asset generation paths");
        return false;
    }
    // F-03-003: refuse-then-escape, before anything is written. Two layers, two
    // grammars: the inner sh that .desktop Exec= and systemd ExecStart= both
    // hand the command to, and the file format itself, which used to get no
    // escaping at all. See linux_asset_escaping_policy.h.
    std::string execShell = shell_quote_single(execPath);
    std::string configShell = shell_quote_single(configPath);
    LinuxAssetEscapedPaths escaped = {};
    const char* pathReject = linux_asset_prepare_paths(
        execPath, execShell.c_str(), configPath, configShell.c_str(), &escaped);
    if (pathReject) {
        set_message(err, errSize, "Cannot generate desktop assets: %s", pathReject);
        return false;
    }
    if (!ensure_directory_recursive(outputDir, err, errSize)) return false;

    // --from-desktop keeps the window open long enough to read an error; on a
    // clean quit the terminal closes immediately, which is what a launcher
    // should do.
    std::string instanceArgs = linux_instance_cli_arguments();
    std::string desktopExec = std::string("sh -lc \"exec ") + escaped.desktopExec +
        " --tui --from-desktop" + instanceArgs + " --config " + escaped.desktopConfig + "\"";
    std::string serviceExec = std::string("/bin/sh -lc \"exec ") + escaped.systemdExec +
        " --apply-config" + instanceArgs + " --config " + escaped.systemdConfig + "\"";

    std::string desktop;
    appendf(&desktop,
        "[Desktop Entry]\n"
        "Type=Application\n"
        "Version=1.0\n"
        "Name=%s\n"
        "Comment=Open the Linux terminal UI for %s\n"
        "Exec=%s\n"
        "Terminal=true\n"
        "Categories=Utility;System;\n"
        "StartupNotify=false\n",
        APP_NAME, APP_NAME, desktopExec.c_str());

    std::string autostart = desktop;
    autostart += "X-GNOME-Autostart-enabled=true\n";

    std::string service;
    appendf(&service,
        "[Unit]\n"
        "Description=%s one-shot profile apply via daemon\n"
        "After=%s\n"
        "Requires=%s\n"
        "ConditionPathExists=%s\n\n"
        "[Service]\n"
        "Type=oneshot\n"
        "ExecStart=%s\n"
        "StandardOutput=journal\n"
        "StandardError=journal\n\n"
        "[Install]\n"
        "WantedBy=multi-user.target\n",
        APP_NAME, linux_instance().paths.unitName, linux_instance().paths.unitName,
        escaped.systemdConditionPath,  // F-03-003: was the RAW path
        serviceExec.c_str());

    std::string entryName = std::string("greencurve") +
        (linux_instance_enabled() ? std::string("-") + linux_instance().uuid.text : "");
    std::string readme;
    appendf(&readme,
        "# Linux Assets\n\n"
        "These files were generated by %s %s.\n\n"
        "- `greencurve.desktop`: visible launcher with `Terminal=true` for GNOME/KDE/Wayland sessions\n"
        "- `greencurve-autostart.desktop`: session autostart launcher that still opens a terminal window\n"
        "- `greencurve-apply.service`: optional one-shot profile apply client that requires `%s`\n\n"
        "The release archive also ships `greencurve-setup.sh`, which performs the\n"
        "install and group enrollment in one step:\n\n"
        "```bash\n"
        "sudo ./greencurve-setup.sh install%s\n"
        "./greencurve-setup.sh status%s\n"
        "```\n\n"
        "Manual equivalent:\n\n"
        "```bash\n"
        "install -Dm644 greencurve.desktop ~/.local/share/applications/%s.desktop\n"
        "install -Dm644 greencurve-autostart.desktop ~/.config/autostart/%s.desktop\n"
        "sudo %s%s --service-install\n"
        "sudo usermod -aG greencurve \"$USER\"\n"
        "# Sign out/in, or run: newgrp greencurve\n"
        "sudo install -Dm644 greencurve-apply.service /etc/systemd/system/%s-apply.service\n"
        "sudo systemctl daemon-reload\n"
        "sudo systemctl enable %s-apply.service\n"
        "```\n\n"
        "The generated one-shot unit is only a convenience hook; normal live control uses the daemon installed by `--service-install`.\n",
        APP_NAME,
        APP_VERSION,
        linux_instance().paths.unitName,
        instanceArgs.c_str(), instanceArgs.c_str(),
        entryName.c_str(), entryName.c_str(), execShell.c_str(), instanceArgs.c_str(),
        entryName.c_str(), entryName.c_str());

    std::string desktopPath = path_join(outputDir, "greencurve.desktop");
    std::string autostartPath = path_join(outputDir, "greencurve-autostart.desktop");
    std::string servicePath = path_join(outputDir, "greencurve-apply.service");
    std::string readmePath = path_join(outputDir, "README.md");

    return write_text_file_atomic(desktopPath.c_str(), desktop, err, errSize) &&
        write_text_file_atomic(autostartPath.c_str(), autostart, err, errSize) &&
        write_text_file_atomic(servicePath.c_str(), service, err, errSize) &&
        write_text_file_atomic(readmePath.c_str(), readme, err, errSize);
}
